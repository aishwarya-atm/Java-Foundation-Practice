public class Problem1_VariableDeclaration{
    public static void main(String[] args){
        int age=35;
        float mark=87.5f;
        char grade='A';
        boolean passed=true;
        System.out.println("Age    = "+age);
        System.out.println("Mark   = "+mark);
        System.out.println("Grade  = "+grade);
        System.out.println("Passed = "+passed);
    }
}