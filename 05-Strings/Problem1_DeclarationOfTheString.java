public class Problem1_DeclarationOfTheString {
    public static void main(String[] args){
        String name = "Aishwarya A T M";
        System.out.println("Name = "+name);
        System.out.println("Length of the string = "+name.length());
        System.out.println("First character of the string = "+name.charAt(0));
        System.out.println("Last character of the string = "+name.charAt(name.length()-1));
    }
}
